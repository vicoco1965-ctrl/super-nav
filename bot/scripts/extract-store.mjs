// Copies the store map and the list parser out of site/index.html into bot/src/store-core.js,
// so the bot and the site always use the same aisles, keywords and list splitting.
// Run: node bot/scripts/extract-store.mjs   (the test fails if the file is out of date)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export function buildCore(html) {
  const cut = (from, to) => {
    const a = html.indexOf(from), b = html.indexOf(to, a + 1);
    if (a < 0 || b < 0) throw new Error(`marker not found: ${a < 0 ? from : to}`);
    return html.slice(a, b).trimEnd();
  };
  const parts = [
    cut("const SPINE", "// ---------- State"),
    cut("// corridors the customer walks", "const pts ="),
    cut("// true when a known product word", "// Speech -> list"),
    cut("const HEB_NUM", "function rebuildPicker"),
    cut("function sideOf", "function stopText"),
  ];
  // the site keeps this shopper's own fixes in localStorage; the bot has only the shared ones (setSharedFixes)
  const mine = "function myFixes() {";
  let body = parts.join("\n\n");
  const at = body.indexOf(mine);
  if (at < 0) throw new Error("marker not found: " + mine);
  body = body.slice(0, at) + "function myFixes() { return {}; }" + body.slice(body.indexOf("\n", at));
  body += "\n\nfunction setSharedFixes(f) { sharedFixes = f && typeof f === \"object\" ? f : {}; }";
  return `// GENERATED from site/index.html by bot/scripts/extract-store.mjs. Do not edit by hand.\n` +
    body +
    `\n\nexport { SPINE, RIGHT, CONNECT, BACK, LEFT, SECTIONS, BYID, ENTRANCE, CHECKOUT, BACK_ORDER, clean, matchSection, leg, startsKw, PHRASES, segment, splitList, HEB_NUM, whereFromWords, sideOf, sidedList, aisleWhere, fixName, fixFor, setSharedFixes };\n`;
}
// Walking distances between every pair of stops, worked out ahead of time: the Worker's free plan
// allows only a few milliseconds of CPU per message, too little to run the path search each time.
export async function buildDistances(coreUrl) {
  const m = await import(coreUrl + "?t=" + Date.now());
  const pts = [m.ENTRANCE, m.CHECKOUT, ...m.SECTIONS.map(s => s.stop)];
  const keys = [...new Set(pts.map(p => p.join(",")))];
  const table = {};
  for (const a of keys) for (const b of keys) {
    const p = m.leg(a.split(",").map(Number), b.split(",").map(Number));
    let d = 0; for (let i = 1; i < p.length; i++) d += Math.abs(p[i][0] - p[i - 1][0]) + Math.abs(p[i][1] - p[i - 1][1]);
    table[a + "|" + b] = d;
  }
  return `// GENERATED by bot/scripts/extract-store.mjs from the map in site/index.html. Do not edit by hand.\nexport const DIST = ${JSON.stringify(table)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = buildCore(readFileSync(join(root, "site", "index.html"), "utf8"));
  const corePath = join(root, "bot", "src", "store-core.js");
  writeFileSync(corePath, out);
  writeFileSync(join(root, "bot", "src", "distances.js"), await buildDistances("file://" + corePath));
  console.log("wrote bot/src/store-core.js and bot/src/distances.js");
}
